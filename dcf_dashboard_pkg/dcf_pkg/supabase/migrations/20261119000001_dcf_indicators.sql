-- D 결핍 · C 연결 · F 실행 지표 표. 열 이름은 engine_dcf.build_*_table 결과와 같다.
-- 값 열마다 <열>__status(확정/가정/미산정)와 <열>__src(출처키를 +로 이음)를 둔다.
-- 이 파일은 scripts/gen_migration_dcf.py가 만든다. 손으로 고치지 않는다.

-- 필요성 파트 입력(판정 아님)
create table if not exists public.need_dc (
  site_id text primary key,
  "d_irreplaceable_pop" integer,
  "d_irreplaceable_pop__status" text,
  "d_irreplaceable_pop__src" text,
  "d_shared_pop" integer,
  "d_shared_pop__status" text,
  "d_shared_pop__src" text,
  "d_unserved_share" double precision,
  "d_unserved_share__status" text,
  "d_unserved_share__src" text,
  "d_area_gap_m2pc" double precision,
  "d_area_gap_m2pc__status" text,
  "d_area_gap_m2pc__src" text,
  "c_dpc_median" double precision,
  "c_dpc_median__status" text,
  "c_dpc_median__src" text,
  "c_rank_spread" integer,
  "c_rank_spread__status" text,
  "c_rank_spread__src" text,
  "c_assumption_dependent" boolean,
  "c_assumption_dependent__status" text,
  "c_assumption_dependent__src" text,
  "c_dpc_d100" double precision,
  "c_dpc_d100__status" text,
  "c_dpc_d100__src" text,
  "c_dpc_d300" double precision,
  "c_dpc_d300__status" text,
  "c_dpc_d300__src" text,
  "c_dpc_d500" double precision,
  "c_dpc_d500__status" text,
  "c_dpc_d500__src" text,
  "c_dpc_d700" double precision,
  "c_dpc_d700__status" text,
  "c_dpc_d700__src" text,
  "c_axis_dist_m" double precision,
  "c_axis_dist_m__status" text,
  "c_axis_dist_m__src" text,
  check ("d_irreplaceable_pop__status" in ('확정','가정','미산정')),
  check ("d_shared_pop__status" in ('확정','가정','미산정')),
  check ("d_unserved_share__status" in ('확정','가정','미산정')),
  check ("d_area_gap_m2pc__status" in ('확정','가정','미산정')),
  check ("c_dpc_median__status" in ('확정','가정','미산정')),
  check ("c_rank_spread__status" in ('확정','가정','미산정')),
  check ("c_assumption_dependent__status" in ('확정','가정','미산정')),
  check ("c_dpc_d100__status" in ('확정','가정','미산정')),
  check ("c_dpc_d300__status" in ('확정','가정','미산정')),
  check ("c_dpc_d500__status" in ('확정','가정','미산정')),
  check ("c_dpc_d700__status" in ('확정','가정','미산정')),
  check ("c_axis_dist_m__status" in ('확정','가정','미산정')),
  data_base_date date not null,
  updated_at timestamptz not null default now()
);
alter table public.need_dc enable row level security;
create policy "need_dc_read" on public.need_dc for select to authenticated using (true);
-- 쓰기는 service_role(서버의 계산 엔진)만 한다. 키는 클라이언트에 두지 않는다.

